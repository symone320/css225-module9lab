# Problem 2: Number List 0 to 10
# This program uses a while loop to create a list containing numbers 0 through 10.

# Create an empty list
L = []

# Start the counter at 0
counter = 0

# Continue the loop until the counter is greater than 10
while counter <= 10:
    L.append(counter)
    counter += 1

# Display the completed list
print(L)
